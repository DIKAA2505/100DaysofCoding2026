public class VariabelDasar {
  public static void main(String[] args) {
    
    String nama;
    int nilai;
    nama = "Dika";
    nilai = 75;

    System.out.println("Nama  : " + nama);
    System.out.println("Nilai : " + nilai);

    nama = "Dika saja"; // ganti nama
    nilai = 90;            // ganti nilai
    System.out.println("\nSetelah diubah:");
    System.out.println("Nama  : " + nama);
    System.out.println("Nilai : " + nilai);
  }
}
